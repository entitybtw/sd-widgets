static BY_RU: LazyLock<HashMap<&'static str, &'static str>> = LazyLock::new(|| {
    let mut map = HashMap::with_capacity(TABLE.len());
    for (ru, uk) in TABLE {
        map.insert(*ru, *uk);
    }
    map
});

/// Keys already reported by [`lookup`], so a label drawn every frame is
/// printed once.
static REPORTED: LazyLock<Mutex<HashSet<String>>> = LazyLock::new(|| Mutex::new(HashSet::new()));

pub(crate) fn lookup(ru: &str) -> Option<&'static str> {
    let found = BY_RU.get(ru).copied();
    if found.is_none() && std::env::var_os("SDW_UK_MISSING").is_some() {
        report(ru);
    }
    found
}

fn report(ru: &str) {
    if let Ok(mut seen) = REPORTED.lock() {
        if seen.insert(ru.to_string()) {
            eprintln!("uk: no translation for \"{ru}\"");
        }
    }
}
